"""转换执行分发；Worker 独立管理队列、解密、拆分和任务状态。"""

from dataclasses import dataclass
from pathlib import Path
from typing import Any, Protocol

from loguru import logger


@dataclass(frozen=True)
class EngineAvailability:
    mineru: bool
    audio: bool
    video: bool
    formats: bool


class ConversionServices(Protocol):
    markitdown: Any

    def _process_with_mineru(self, file_path: str, options: dict) -> dict: ...
    def _process_audio(self, file_path: str, options: dict) -> dict: ...
    def _process_video(self, file_path: str, options: dict) -> dict: ...
    def _process_with_markitdown(self, file_path: str) -> dict: ...
    def _process_with_format_engine(self, file_path: str, options: dict, engine_name: str | None = None) -> dict: ...
    def _convert_office_to_new_format(self, file_path: str) -> str: ...


def dispatch_conversion(
    services: ConversionServices,
    file_path: str,
    backend: str,
    options: dict,
    *,
    available: EngineAvailability,
    registry: Any,
    route_spreadsheet: bool,
    is_mineru_backend: bool,
) -> dict:
    file_ext = Path(file_path).suffix.lower()
    # 5. 引擎路由
    result = None

    if route_spreadsheet:
        if not services.markitdown:
            raise ValueError(f"MarkItDown not available, cannot parse {file_ext} spreadsheet")
        logger.info(f"📊 {file_ext.upper()} spreadsheet detected, parsing with MarkItDown (backend={backend})")
        result = services._process_with_markitdown(file_path)

    elif available.formats and registry.is_supported(file_path):
        # 专业格式按文件本身选择解析引擎，避免通用 MinerU 预设把生物序列交给文档解析器。
        result = services._process_with_format_engine(file_path, options)

    elif backend == "sensevoice":
        if not available.audio:
            raise ValueError("SenseVoice not available")
        result = services._process_audio(file_path, options)

    elif backend == "video":
        if not available.video:
            raise ValueError("Video engine not available")
        result = services._process_video(file_path, options)

    elif is_mineru_backend and file_ext in {
        ".pdf",
        ".png",
        ".jpg",
        ".jpeg",
        ".bmp",
        ".tiff",
        ".tif",
        ".webp",
        ".docx",
        ".pptx",
    }:
        if not available.mineru:
            raise ValueError("MinerU Pipeline not available")
        options["parse_mode"] = backend
        result = services._process_with_mineru(file_path, options)

    elif backend == "auto" or is_mineru_backend:
        if file_ext in [".wav", ".mp3", ".flac", ".m4a", ".ogg"] and available.audio:
            result = services._process_audio(file_path, options)
        elif file_ext in [".mp4", ".avi", ".mkv", ".mov", ".webm"] and available.video:
            result = services._process_video(file_path, options)
        elif (
            file_ext in [".pdf", ".png", ".jpg", ".jpeg", ".bmp", ".tiff", ".tif", ".webp", ".docx", ".pptx"]
            and available.mineru
        ):
            options["parse_mode"] = "pipeline"
            result = services._process_with_mineru(file_path, options)
        elif file_ext in [".doc", ".ppt"]:
            # 旧版 Office 格式先用 LibreOffice 转为对应 OOXML 新格式，再走 MinerU 原生解析
            try:
                new_path = services._convert_office_to_new_format(file_path)
            except Exception as e:
                logger.warning(f"⚠️ Old Office conversion failed ({e}); MarkItDown fallback is skipped")
                raise

            try:
                try:
                    if not available.mineru:
                        raise ValueError("MinerU Pipeline not available for converted Office file")
                    options["parse_mode"] = "pipeline"
                    result = services._process_with_mineru(new_path, options)
                    if not result:
                        raise ValueError("No result generated by MinerU for converted Office file")
                except Exception as e:
                    if not services.markitdown:
                        raise
                    logger.warning(
                        f"⚠️ Converted Office parsing failed ({e}); falling back to MarkItDown with {new_path}"
                    )
                    result = services._process_with_markitdown(new_path)
            finally:
                # 转换产物是中间件，解析完即可删除；否则会永久堆积在上传目录
                try:
                    Path(new_path).unlink(missing_ok=True)
                except OSError as cleanup_err:
                    logger.debug(f"清理转换产物失败 {new_path}: {cleanup_err}")
        elif file_ext in [".epub"] and services.markitdown:
            # EPUB 电子书走 MarkItDown 原生支持
            result = services._process_with_markitdown(file_path)
        elif services.markitdown:
            result = services._process_with_markitdown(file_path)
        else:
            raise ValueError(f"Unsupported file type for Auto mode: {file_ext}")

    else:
        if available.formats:
            engine = registry.get_engine(backend)
            if engine:
                result = services._process_with_format_engine(file_path, options, engine_name=backend)
            else:
                raise ValueError(f"Unknown backend: {backend}")
        else:
            raise ValueError(f"Unknown backend: {backend}")

    return result
